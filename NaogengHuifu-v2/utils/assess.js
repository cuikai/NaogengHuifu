/** 移动能力层：取「最高能稳定做到的」 */
function levelM(a) {
  if (a.walk >= 4 && a.stair >= 3) return 5;
  if (a.walk >= 2 || a.stair >= 2) return 4;
  if (a.stand >= 2) return 3;
  if (a.sit >= 2) return 2;
  return 1;
}

/** 上肢手功能层：Q6 直接映射 */
function levelH(a) {
  return (a.hand == null ? 0 : a.hand) + 1;
}

/** 曲线用的分值：只在「记录」页画趋势，不对外呈现为评分 */
function trend(a) {
  return (a.stand || 0) + (a.walk || 0) + (a.hand || 0);
}

