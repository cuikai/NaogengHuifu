/** 曲线用的分值：只在「记录」页画趋势，不对外呈现为评分。
 *  三题的最高档分别是 3 / 4 / 4，所以满分是 11 —— record 页画柱子用同一个常数。 */
const TREND_MAX = 11;
function trend(a) {
  return Math.max(0, pick(a, 'stand')) + Math.max(0, pick(a, 'walk')) + Math.max(0, pick(a, 'hand'));
}

/** 勾了的标记里，哪些是「要先看医生」那一类 */
function urgentFlags(flags) {
  return (flags || []).map(function (f) { return FLAG_RULE[f]; })
    .filter(function (r) { return r && r.urgent; });
}

