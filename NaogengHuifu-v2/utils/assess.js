/* ------------------------------------------------------------------ *
 * 分层判定
 * ------------------------------------------------------------------ */

function pick(a, k) { return (a && a[k] != null) ? a[k] : -1; }

/**
 * 移动能力层。
 *
 * 两步：先按「最高能做到的」给一个候选层，再用低层级的能力把它封顶。
 * 家属勾选常常互相矛盾（楼梯那题最容易勾高），矛盾时一律取低的那一层 ——
 * 判低了只是内容简单一点，判高了是让站不稳的人去做单腿站立。
 */
function levelM(a) {
  const situp = pick(a, 'situp'), sit = pick(a, 'sit');
  const stand = pick(a, 'stand'), walk = pick(a, 'walk'), stair = pick(a, 'stair');

  let lv;
  if (walk >= 4 && stair >= 3) lv = 5;
  else if (walk >= 2 || stair >= 2) lv = 4;
  else if (stand >= 2) lv = 3;
  else if (sit >= 2) lv = 2;
  else lv = 1;

  // ── 封顶：低层级的能力说了算 ──
  if (situp === 0) lv = Math.min(lv, 1);          // 完全坐不起来
  if (sit === 0) lv = Math.min(lv, 1);            // 坐不住
  if (sit === 1) lv = Math.min(lv, 2);            // 坐着要人扶
  if (stand === 0) lv = Math.min(lv, 2);          // 完全站不起来 → 不给任何站立内容
  if (stand === 1) lv = Math.min(lv, 3);          // 站要人扶 → 不给步行、单腿
  if (walk === 0 || walk === 1) lv = Math.min(lv, 3);  // 走不了 / 要人搀

  return Math.max(1, lv);
}

/** 上肢手功能层：Q6 直接映射 */
function levelH(a) {
  const h = pick(a, 'hand');
  return (h < 0 ? 0 : h) + 1;
}

/**
 * 发病 2 周内。
 *
 * AVERT 试验（Lancet 2015）提示发病 24 小时内的高强度离床活动可能有害；
 * 《成人脑卒中患者运动康复循证实践指南》推荐在生命体征稳定、症状不再进展的
 * 前提下于 24～48 小时后启动，且早期强度应由医院定。
 * 所以这段时间软件不擅自给站立/平衡的进阶内容。
 */
function isAcute(a) { return pick(a, 'phase') === 0; }

